-- ROVY STORE: customer returns and exchanges workflow.
CREATE TABLE IF NOT EXISTS private.return_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
  customer_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  request_type text NOT NULL CHECK (request_type IN ('return','exchange')),
  reason text NOT NULL CHECK (reason IN ('wrong_size','defective','damaged','not_as_described','changed_mind','other')),
  details text,
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN (
    'submitted','approved','rejected','in_transit','received','inspected',
    'refund_approved','refunded','exchange_pending','exchanged'
  )),
  return_shipping_payer text NOT NULL CHECK (return_shipping_payer IN ('store','customer')),
  return_tracking_number text,
  reviewed_by uuid REFERENCES auth.users(id),
  reviewed_at timestamptz,
  review_notes text,
  received_by uuid REFERENCES auth.users(id),
  received_at timestamptz,
  inspected_by uuid REFERENCES auth.users(id),
  inspected_at timestamptz,
  inspection_notes text,
  refund_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
  refund_payment_method text CHECK (refund_payment_method IN ('vodafone_cash','instapay','bank_transfer','cash')),
  refund_payment_reference text,
  refund_paid_by uuid REFERENCES auth.users(id),
  refund_paid_at timestamptz,
  replacement_order_id bigint REFERENCES public.orders(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT return_refund_paid_fields CHECK (
    status <> 'refunded' OR (
      refund_amount > 0 AND refund_payment_method IS NOT NULL
      AND nullif(btrim(refund_payment_reference),'') IS NOT NULL
      AND refund_paid_by IS NOT NULL AND refund_paid_at IS NOT NULL
    )
  ),
  CONSTRAINT return_exchange_link CHECK (
    status <> 'exchanged' OR (request_type='exchange' AND replacement_order_id IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS private.return_request_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_request_id bigint NOT NULL REFERENCES private.return_requests(id) ON DELETE RESTRICT,
  order_item_id bigint NOT NULL REFERENCES public.order_items(id) ON DELETE RESTRICT,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  product_name_snapshot text NOT NULL,
  size text,
  color text,
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  requested_quantity integer NOT NULL CHECK (requested_quantity > 0),
  accepted_quantity integer NOT NULL DEFAULT 0 CHECK (accepted_quantity >= 0 AND accepted_quantity <= requested_quantity),
  restocked_quantity integer NOT NULL DEFAULT 0 CHECK (restocked_quantity >= 0 AND restocked_quantity <= accepted_quantity),
  inspection_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(return_request_id,order_item_id)
);

CREATE TABLE IF NOT EXISTS private.return_request_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_request_id bigint NOT NULL REFERENCES private.return_requests(id) ON DELETE RESTRICT,
  from_status text,
  to_status text NOT NULL,
  actor_user_id uuid REFERENCES auth.users(id),
  note text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_return_requests_one_open_per_order
ON private.return_requests(order_id)
WHERE status IN ('submitted','approved','in_transit','received','inspected','refund_approved','exchange_pending');

CREATE INDEX IF NOT EXISTS idx_return_requests_customer_created
ON private.return_requests(customer_user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_return_requests_status_created
ON private.return_requests(status,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_return_request_items_request
ON private.return_request_items(return_request_id);
CREATE INDEX IF NOT EXISTS idx_return_request_items_order_item
ON private.return_request_items(order_item_id);

ALTER TABLE private.return_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE private.return_request_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE private.return_request_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON private.return_requests,private.return_request_items,private.return_request_events FROM PUBLIC,anon,authenticated;
GRANT ALL ON private.return_requests,private.return_request_items,private.return_request_events TO service_role;

CREATE OR REPLACE FUNCTION public.customer_create_return_request(
  p_order_id bigint,p_request_type text,p_reason text,p_details text,p_items jsonb
) RETURNS json
LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE
  v_uid uuid:=auth.uid();
  v_order public.orders%rowtype;
  v_request_id bigint;
  v_item jsonb;
  v_order_item public.order_items%rowtype;
  v_qty integer;
  v_previously_requested integer;
  v_name text;
  v_shipping_payer text;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'يجب تسجيل الدخول أولاً'; END IF;
  IF NOT EXISTS (SELECT 1 FROM auth.users u WHERE u.id=v_uid AND u.email_confirmed_at IS NOT NULL) THEN
    RAISE EXCEPTION 'يجب تأكيد البريد الإلكتروني أولاً';
  END IF;
  IF p_request_type NOT IN ('return','exchange') THEN RAISE EXCEPTION 'نوع الطلب غير صحيح'; END IF;
  IF p_reason NOT IN ('wrong_size','defective','damaged','not_as_described','changed_mind','other') THEN
    RAISE EXCEPTION 'سبب الطلب غير صحيح';
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items)<>'array' OR jsonb_array_length(p_items)<1 OR jsonb_array_length(p_items)>30 THEN
    RAISE EXCEPTION 'اختر منتجاً واحداً على الأقل';
  END IF;
  IF length(coalesce(p_details,''))>1500 THEN RAISE EXCEPTION 'التفاصيل طويلة جداً'; END IF;

  SELECT * INTO v_order FROM public.orders
   WHERE id=p_order_id AND customer_user_id=v_uid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'الطلب غير موجود في حسابك'; END IF;
  IF v_order.status<>'delivered' OR v_order.delivered_at IS NULL THEN
    RAISE EXCEPTION 'يمكن طلب الاسترجاع أو الاستبدال بعد استلام الطلب فقط';
  END IF;
  IF now()>v_order.delivered_at+interval '14 days' THEN
    RAISE EXCEPTION 'انتهت مهلة الاسترجاع والاستبدال (14 يوماً من الاستلام)';
  END IF;
  IF EXISTS (SELECT 1 FROM private.return_requests r WHERE r.order_id=p_order_id
    AND r.status IN ('submitted','approved','in_transit','received','inspected','refund_approved','exchange_pending')) THEN
    RAISE EXCEPTION 'يوجد بالفعل طلب استرجاع أو استبدال مفتوح لهذا الطلب';
  END IF;

  v_shipping_payer:=CASE WHEN p_reason IN ('defective','damaged','not_as_described','wrong_size') THEN 'store' ELSE 'customer' END;
  INSERT INTO private.return_requests(order_id,customer_user_id,request_type,reason,details,return_shipping_payer)
  VALUES(p_order_id,v_uid,p_request_type,p_reason,nullif(btrim(coalesce(p_details,'')),''),v_shipping_payer)
  RETURNING id INTO v_request_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    IF nullif(v_item->>'order_item_id','') IS NULL OR nullif(v_item->>'quantity','') IS NULL THEN
      RAISE EXCEPTION 'بيانات المنتج المختار غير مكتملة';
    END IF;
    SELECT * INTO v_order_item FROM public.order_items
      WHERE id=(v_item->>'order_item_id')::bigint AND order_id=p_order_id FOR UPDATE;
    IF NOT FOUND OR v_order_item.product_id IS NULL THEN RAISE EXCEPTION 'المنتج غير تابع لهذا الطلب'; END IF;
    v_qty:=(v_item->>'quantity')::integer;
    IF v_qty<1 OR v_qty>v_order_item.quantity THEN RAISE EXCEPTION 'الكمية المطلوبة غير صحيحة'; END IF;
    SELECT coalesce(sum(ri.requested_quantity),0)::integer INTO v_previously_requested
      FROM private.return_request_items ri JOIN private.return_requests rr ON rr.id=ri.return_request_id
     WHERE ri.order_item_id=v_order_item.id AND rr.status<>'rejected';
    IF v_qty+v_previously_requested>v_order_item.quantity THEN
      RAISE EXCEPTION 'الكمية المطلوبة أكبر من الكمية المتاحة للإرجاع';
    END IF;
    SELECT name INTO v_name FROM public.products WHERE id=v_order_item.product_id;
    INSERT INTO private.return_request_items(
      return_request_id,order_item_id,product_id,product_name_snapshot,size,color,unit_price,requested_quantity
    ) VALUES(v_request_id,v_order_item.id,v_order_item.product_id,coalesce(v_name,'منتج'),v_order_item.size,v_order_item.color,v_order_item.price,v_qty);
  END LOOP;

  IF NOT EXISTS (SELECT 1 FROM private.return_request_items WHERE return_request_id=v_request_id) THEN
    RAISE EXCEPTION 'لم يتم اختيار منتجات صالحة';
  END IF;
  INSERT INTO private.return_request_events(return_request_id,from_status,to_status,actor_user_id,note)
  VALUES(v_request_id,NULL,'submitted',v_uid,'طلب العميل عبر الموقع');
  RETURN json_build_object('success',true,'return_request_id',v_request_id,'status','submitted','return_shipping_payer',v_shipping_payer);
END;
$function$;

CREATE OR REPLACE FUNCTION public.customer_list_return_requests()
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v_uid uuid:=auth.uid(); v_result json;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'يجب تسجيل الدخول'; END IF;
  SELECT coalesce(json_agg(row_to_json(x) ORDER BY x.created_at DESC),'[]'::json) INTO v_result
  FROM (
    SELECT r.id,r.order_id,r.request_type,r.reason,r.details,r.status,r.return_shipping_payer,
      r.return_tracking_number,r.review_notes,r.inspection_notes,r.refund_amount,r.refund_payment_method,
      r.refund_payment_reference,r.refund_paid_at,r.replacement_order_id,r.created_at,r.updated_at,
      coalesce((SELECT json_agg(json_build_object('id',i.id,'order_item_id',i.order_item_id,
        'product_name',i.product_name_snapshot,'size',i.size,'color',i.color,
        'requested_quantity',i.requested_quantity,'accepted_quantity',i.accepted_quantity,
        'unit_price',i.unit_price) ORDER BY i.id)
        FROM private.return_request_items i WHERE i.return_request_id=r.id),'[]'::json) items
    FROM private.return_requests r WHERE r.customer_user_id=v_uid
  ) x;
  RETURN v_result;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_list_return_requests()
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v_role text:=public.current_staff_role(); v_result json;
BEGIN
  IF auth.uid() IS NULL OR coalesce(v_role,'') NOT IN ('owner','manager','customer_service','shipping') THEN
    RAISE EXCEPTION 'Access denied';
  END IF;
  SELECT coalesce(json_agg(row_to_json(x) ORDER BY x.created_at DESC),'[]'::json) INTO v_result
  FROM (
    SELECT r.id,r.order_id,r.customer_user_id,r.request_type,r.reason,r.details,r.status,
      r.return_shipping_payer,r.return_tracking_number,r.reviewed_at,r.review_notes,
      r.received_at,r.inspected_at,r.inspection_notes,r.refund_amount,r.refund_payment_method,
      r.refund_payment_reference,r.refund_paid_at,r.replacement_order_id,r.created_at,
      o.customer_name,o.customer_phone,o.customer_address,o.delivered_at,
      coalesce((SELECT json_agg(json_build_object('id',i.id,'order_item_id',i.order_item_id,
        'product_id',i.product_id,'product_name',i.product_name_snapshot,'size',i.size,'color',i.color,
        'unit_price',i.unit_price,'requested_quantity',i.requested_quantity,
        'accepted_quantity',i.accepted_quantity,'restocked_quantity',i.restocked_quantity,
        'inspection_note',i.inspection_note) ORDER BY i.id)
        FROM private.return_request_items i WHERE i.return_request_id=r.id),'[]'::json) items
    FROM private.return_requests r JOIN public.orders o ON o.id=r.order_id
  ) x;
  RETURN v_result;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_review_return_request(p_request_id bigint,p_approved boolean,p_notes text DEFAULT NULL)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v_role text:=public.current_staff_role(); v_req private.return_requests%rowtype; v_next text;
BEGIN
  IF auth.uid() IS NULL OR coalesce(v_role,'') NOT IN ('owner','manager','customer_service') THEN RAISE EXCEPTION 'Access denied'; END IF;
  SELECT * INTO v_req FROM private.return_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'طلب المرتجع غير موجود'; END IF;
  IF v_req.status<>'submitted' THEN RAISE EXCEPTION 'هذا الطلب تمت مراجعته بالفعل'; END IF;
  IF NOT p_approved AND nullif(btrim(coalesce(p_notes,'')),'') IS NULL THEN RAISE EXCEPTION 'اكتب سبب الرفض'; END IF;
  v_next:=CASE WHEN p_approved THEN 'approved' ELSE 'rejected' END;
  UPDATE private.return_requests SET status=v_next,reviewed_by=auth.uid(),reviewed_at=now(),
    review_notes=nullif(btrim(coalesce(p_notes,'')),''),updated_at=now() WHERE id=p_request_id;
  INSERT INTO private.return_request_events(return_request_id,from_status,to_status,actor_user_id,note)
  VALUES(p_request_id,v_req.status,v_next,auth.uid(),nullif(btrim(coalesce(p_notes,'')),''));
  RETURN json_build_object('success',true,'status',v_next);
END;
$function$;

